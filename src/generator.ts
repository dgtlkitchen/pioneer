/**
 * Main generator function.
 * Scans proto directories, writes a summary file, and invokes sub-generators.
 */
export const generate = async ({
	protoDirs,
	outPath,
	options,
	moduleIgnoreList
}: ProtoGenInput): Promise<void> => {
	console.log("Starting Pioneer proto-gen with options:", JSON.stringify(options, null, 2))
	console.log("Scanning proto directories:", protoDirs)

	// Scan proto files from the provided directories.
	const protoFiles: string[] = []
	const walkDir = async (dir: string): Promise<void> => {
		const entries = await fs.readdir(dir, { withFileTypes: true })
		for (const entry of entries) {
			const fullPath = join(dir, entry.name)
			if (entry.isDirectory()) {
				await walkDir(fullPath)
			} else if (entry.isFile() && fullPath.endsWith(".proto")) {
				protoFiles.push(fullPath)
			}
		}
	}
	for (const dir of protoDirs) {
		try {
			await walkDir(dir)
		} catch (err) {
			console.error(`Error reading directory ${dir}:`, err)
		}
	}
	console.log(`Found ${protoFiles.length} proto files.`)

	// Write a summary file in the output directory.
	const summaryContent = `// Generated by proto-gen
// Found proto files:
${protoFiles.map((f) => `// - ${f}`).join("\n")}
`
	await fs.mkdir(outPath, { recursive: true })
	await fs.writeFile(join(outPath, "generatedSummary.ts"), summaryContent, "utf-8")
	console.log("Generated summary file.")

	const mods = options.modules || {
		common: true,
		grpc: true,
		grpcWeb: true,
		rest: true,
		rpc: true
	}

	await generateCommon(outPath)
	if (mods.grpc) await generateGrpc(outPath, [...protoDirs], moduleIgnoreList ?? [])
	if (mods.grpcWeb) await generateGrpcWeb(outPath)
	if (mods.rest) await generateRest(outPath)
	if (mods.rpc) await generateRpc(outPath)

	console.log("Proto-gen generation completed!")
}
