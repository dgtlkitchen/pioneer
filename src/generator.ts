import { spawn } from "node:child_process"
import { promises as fs } from "node:fs"
import { join, relative } from "node:path"
import type { ProtoGenInput } from "./types/index.ts"

/**
 * Runs Buf to generate Protobuf ES code (messages and service descriptors).
 */
const runBufGenerate = async (): Promise<void> => {
	console.log("Running buf generate...")
	return new Promise<void>((resolve, reject) => {
		const proc = spawn("buf", ["generate"], { stdio: "inherit" })
		proc.on("exit", (code) => {
			if (code === 0) {
				console.log("buf generate finished successfully.")
				resolve()
			} else {
				reject(new Error(`buf generate exited with code ${code}`))
			}
		})
	})
}

/**
 * Generates the common types (protobuf-es output) by invoking buf.
 */
const generateCommon = async (outPath: string) => {
	const commonDir = join(outPath, "common")
	await fs.mkdir(commonDir, { recursive: true })
	await runBufGenerate()
	console.log("Generated common types.")
}

/**
 * Generates Connect-compatible gRPC client stubs.
 */
const generateGrpc = async (
	outPath: string,
	protoDirs: string[],
	moduleIgnoreList: string[]
): Promise<void> => {
	const grpcDir = join(outPath, "grpc")
	// 1. Clean and recreate the grpc output directory
	await fs.rm(grpcDir, { recursive: true, force: true })
	await fs.mkdir(grpcDir, { recursive: true })

	// Prepare to collect export entries for index
	const indexExports: { funcName: string; importPath: string }[] = []

	// 2. Find all proto service definitions
	for (const protoDir of protoDirs) {
		// Recursively traverse protoDir for .proto files
		const entries = await fs.readdir(protoDir, { withFileTypes: true })
		for (const entry of entries) {
			const fullPath = join(protoDir, entry.name)
			if (entry.isDirectory()) {
				// Recurse into subdirectories
				protoDirs.push(fullPath)
			} else if (entry.isFile() && entry.name.endsWith(".proto")) {
				const protoFilePath = fullPath
				const protoText = await fs.readFile(protoFilePath, "utf-8")

				// Extract package name (if any) and all service names in this file
				let packageName = ""
				const serviceNames: string[] = []
				// Remove block comments to avoid false matches
				const textNoBlock = protoText.replace(/\/\*[\s\S]*?\*\//g, "")
				for (const line of textNoBlock.split(/\r?\n/)) {
					const codeLine = line.split("//")[0].trim() // remove line comments
					if (codeLine.startsWith("package ")) {
						const match = codeLine.match(/^package\s+([^;]+);/)
						if (match) {
							packageName = match[1].trim()
						}
					}
					if (codeLine.startsWith("service ")) {
						const match = codeLine.match(/^service\s+(\w+)\s*\{/)
						if (match) {
							serviceNames.push(match[1])
						}
					}
				}
				if (serviceNames.length === 0) continue // no services in this proto

				// Compute the output sub-directory for this proto's package (if package exists)
				const packagePath = packageName ? packageName.split(".").join("/") : ""
				const moduleName =
					packagePath.split("/")[1].charAt(0).toUpperCase() +
					packagePath.split("/")[1].slice(1)

				const modulePath = packagePath.split("/").slice(0, 2).join("/")
				if (moduleIgnoreList.includes(modulePath)) continue

				const serviceOutDir = packagePath ? join(grpcDir, packagePath) : grpcDir
				await fs.mkdir(serviceOutDir, { recursive: true })

				// Base import path for the generated common types file corresponding to this proto
				const protoBaseName = entry.name.replace(".proto", "")
				const commonImportPath = relative(
					serviceOutDir,
					join(outPath, "common", packagePath, `${protoBaseName}_pb.ts`)
				)
					.replace(/\\/g, "/")
					.replace(/\.ts$/, "")

				// Generate a client factory for each service in this proto
				for (const serviceName of serviceNames) {
					const funcName = `create${moduleName}${serviceName}Client`
					const fileHeader = "// This file was generated by proto-gen. DO NOT EDIT.\n"
					const imports =
						`import { createClient } from "@connectrpc/connect"\n` +
						`import { createGrpcTransport } from "@connectrpc/connect-node"\n`
					const serviceImport = `import { ${serviceName} } from "${commonImportPath}"\n\n`
					const functionCode = `export const ${funcName} = ({ baseUrl }: { baseUrl: string }) => {\n  const transport = createGrpcTransport({ baseUrl })\n  return createClient(${serviceName}, transport)\n}\n`

					const clientSource = fileHeader + imports + serviceImport + functionCode
					const outFilePath = join(serviceOutDir, `${serviceName}.ts`)
					await fs.writeFile(outFilePath, clientSource, "utf-8")

					// Collect for index export
					const importPath = `./${packagePath ? `${packagePath}/` : ""}${serviceName}`
					indexExports.push({ funcName, importPath })
				}
			}
		}
	}

	// 4. Generate an index.ts that re-exports all client factory functions
	let indexSource = "// This file was generated by proto-gen. DO NOT EDIT.\n"
	// Sort exports by import path for neatness
	indexExports.sort((a, b) => a.importPath.localeCompare(b.importPath))
	for (const { funcName, importPath } of indexExports) {
		indexSource += `export { ${funcName} } from "${importPath}";\n`
	}
	await fs.writeFile(join(grpcDir, "index.ts"), indexSource, "utf-8")

	console.log("Generated grpc clients.")
}

