import { posix } from "node:path"
import type { Operation } from "./rest.js"

const kebab = (value: string) =>
	value
		.replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
		.replace(/([a-z0-9])([A-Z])/g, "$1-$2")
		.replaceAll("_", "-")
		.toLowerCase()
const pascal = (value: string) =>
	kebab(value)
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join("")
const camel = (value: string) => {
	const result = pascal(value)
	return result[0].toLowerCase() + result.slice(1)
}
const marker = "// Generated by Pioneer. DO NOT EDIT."
const count = <T>(values: T[], key: (value: T) => string) => {
	const counts = new Map<string, number>()
	for (const value of values)
		counts.set(key(value), (counts.get(key(value)) ?? 0) + 1)
	return (value: T) => counts.get(key(value)) ?? 0
}

/** React is an optional output surface, never an import from the core SDK root. */
export function generateReact(operations: Operation[]): Map<string, string> {
	const files = new Map<string, string>()
	const source = operations.map((entry) => {
		const parts = entry.service.split(".")
		return {
			...entry,
			namespace: parts[0],
			module: parts.slice(1, -2).map(kebab).join("-") || kebab(parts[0]),
			version: parts.at(-2) ?? "",
			name: pascal(entry.method)
		}
	})
	const nonCosmos = new Set(
		source
			.filter((entry) => entry.namespace !== "cosmos")
			.map((entry) => entry.module)
	)
	const records = source.map((entry) => ({
		...entry,
		module:
			entry.namespace === "cosmos" && nonCosmos.has(entry.module)
				? `cosmos-${entry.module}`
				: entry.module
	}))
	const collisions = count(
		records,
		(entry) => `${entry.module}\0${entry.kind}\0${entry.name}`
	)
	const versionCollisions = count(
		records,
		(entry) => `${entry.module}\0${entry.kind}\0${entry.name}\0${entry.version}`
	)
	const names = records.map((entry) => ({
		...entry,
		name:
			entry.name +
			(collisions(entry) > 1 ? pascal(entry.version) : "") +
			(versionCollisions(entry) > 1
				? pascal(entry.service.split(".").at(-1) ?? "")
				: "")
	}))
	const byModule = new Map<string, typeof names>()
	for (const entry of names) {
		const entries = byModule.get(entry.module)
		if (entries) entries.push(entry)
		else byModule.set(entry.module, [entry])
	}
	const manifest = []
	const modules = [...byModule.keys()].sort()
	for (const module of modules) {
		const entries = byModule.get(module) ?? []
		const hasTx = entries.some((entry) => entry.kind === "tx")
		const keys = `${camel(module)}Keys`
		files.set(
			`react/${module}/keys.ts`,
			`${marker}\nimport type { ChainHookContext } from "../context.js"\nimport { type SdkModuleKey, sdkKeys } from "../options.js"\nexport const ${keys}: { all: (context: ChainHookContext) => SdkModuleKey } = { all: (context: ChainHookContext) => sdkKeys.module(context, ${JSON.stringify(module)}) }\n`
		)
		for (const entry of entries) {
			const path = `react/${module}/${hasTx ? `${entry.kind}/` : ""}use-${kebab(entry.name)}.ts`
			if (files.has(path)) throw new Error(`Hook naming collision: ${path}`)
			const spec = (target: string) => {
				const value = posix.relative(posix.dirname(path), target)
				return value.startsWith(".") ? value : `./${value}`
			}
			const method = `${entry.symbol}.method.${entry.localName}`
			const context =
				entry.transport === "message" ? "ChainTxContext" : "ChainHookContext"
			const options = `${camel(entry.name)}${entry.kind === "query" ? "Query" : "Mutation"}Options`
			const id = JSON.stringify(`${entry.service}/${entry.method}`)
			const factory = entry.rpcFactory ?? entry.factory
			const transport =
				entry.rpcFactory || entry.transport === "rpc"
					? "context.rpc"
					: `requireRest(context, ${id})`
			const query = entry.kind === "query"
			const lines = [
				marker,
				`import type { MessageInitShape, MessageShape } from "${spec("index.js")}"`,
				`import { ${factory} } from "${spec(`${entry.file}_client.js`)}"`,
				`import { ${entry.symbol} } from "${spec(`${entry.file}_pb.js`)}"`,
				`import type { ${query ? "UseSuspenseQueryResult" : "UseMutationResult"} } from "@tanstack/react-query"`,
				`import { ${entry.transport === "rest" && !entry.rpcFactory ? "requireRest, " : ""}type ${context} } from "${spec("react/context.js")}"`,
				`import { sdkKeys, ${query ? "type SdkQueryOptions, sdkQueryOptions, useSdkQuery" : `type SdkMutationOptions, ${entry.transport === "message" ? "sdkMessageMutationOptions" : "sdkServiceMutationOptions"}, useSdkMutation`} } from "${spec("react/options.js")}"`,
				`export type ${entry.name}Request = MessageInitShape<typeof ${method}.input>`,
				entry.transport === "message"
					? `export type ${entry.name}MessageResponse = MessageShape<typeof ${method}.output>\nexport type ${entry.name}Response = Awaited<ReturnType<ChainTxContext["submit"]>>`
					: `export type ${entry.name}Response = MessageShape<typeof ${method}.output>`
			]
			if (query) {
				lines.push(
					`export function ${options}(context: ${context}, input: ${entry.name}Request): SdkQueryOptions<typeof ${method}.output> { return sdkQueryOptions(sdkKeys.query(context, ${JSON.stringify(module)}, ${id}, ${method}.input, input), ${method}, input, ${factory}(${transport}).${entry.localName}) }`,
					`export function use${entry.name}(context: ${context}, input: ${entry.name}Request): UseSuspenseQueryResult<${entry.name}Response, Error> { return useSdkQuery(${options}(context, input)) }`
				)
			} else {
				const key = `sdkKeys.tx(context, ${JSON.stringify(module)}, ${id}${entry.transport === "message" ? ", context.signerAddress" : ""})`
				lines.push(
					`export function ${options}(context: ${context}): SdkMutationOptions<${entry.name}Response, ${entry.name}Request> { return ${entry.transport === "message" ? `sdkMessageMutationOptions(context, ${key}, ${factory}.${entry.localName})` : `sdkServiceMutationOptions(${key}, ${factory}(${transport}).${entry.localName})`} }`,
					`export function use${entry.name}(context: ${context}): UseMutationResult<${entry.name}Response, Error, ${entry.name}Request> { return useSdkMutation(context, ${options}(context)) }`
				)
				if (entry.transport === "message") {
					const nativeOptions = `${camel(entry.name)}NativeMutationOptions`
					lines.push(
						`import type { NativeChainTxContext } from "${spec("react/context.js")}"`,
						`import { sdkNativeMessageMutationOptions, useSdkNativeMutation, type NativeMessageReceipt, type NativeMessageMutationOptions, type NativeMutationVariables } from "${spec("react/options.js")}"`,
						`export type ${entry.name}NativeResponse = NativeMessageReceipt<typeof ${method}.output>`,
						`export function ${nativeOptions}(context: NativeChainTxContext): NativeMessageMutationOptions<typeof ${method}.input, typeof ${method}.output> { return sdkNativeMessageMutationOptions(context, ${key}, ${method}) }`,
						`export function use${entry.name}Native(context: NativeChainTxContext): UseMutationResult<${entry.name}NativeResponse, Error, NativeMutationVariables<${entry.name}Request>> { return useSdkNativeMutation(${nativeOptions}(context)) }`
					)
				}
			}
			files.set(path, `${lines.join("\n")}\n`)
			manifest.push({
				operation: `${entry.service}/${entry.method}`,
				path,
				export: `use${entry.name}`,
				kind: entry.kind,
				module,
				input: entry.input,
				output: entry.output
			})
		}
	}
	files.set(
		"react/index.ts",
		'export * from "./context.js"\nexport * from "./options.js"\n'
	)
	files.set(
		"react/hooks.json",
		`${JSON.stringify({ modules, operations: manifest }, null, 2)}\n`
	)
	return files
}
