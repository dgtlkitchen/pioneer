import { promises as fs } from "node:fs"
import { dirname, join, relative } from "node:path"
import type { Operation } from "./rest.js"

const kebab = (value: string) =>
	value
		.replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
		.replace(/([a-z0-9])([A-Z])/g, "$1-$2")
		.replaceAll("_", "-")
		.toLowerCase()
const pascal = (value: string) =>
	kebab(value)
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join("")
const camel = (value: string) => {
	const result = pascal(value)
	return result[0].toLowerCase() + result.slice(1)
}
const marker = "// Generated by Pioneer. DO NOT EDIT."

/** React is an optional output surface, never an import from the core SDK root. */
export async function generateReact(output: string, operations: Operation[]) {
	const source = operations.map((entry) => {
		const parts = entry.service.split(".")
		return {
			...entry,
			namespace: parts[0],
			module: parts.slice(1, -2).map(kebab).join("-") || kebab(parts[0]),
			version: parts.at(-2) ?? "",
			name: pascal(entry.method)
		}
	})
	const records = source.map((entry) => ({
		...entry,
		module:
			entry.namespace === "cosmos" &&
			source.some(
				(other) => other.module === entry.module && other.namespace !== "cosmos"
			)
				? `cosmos-${entry.module}`
				: entry.module
	}))
	const names = records.map((entry) => {
		const collisions = records.filter(
			(other) =>
				other.module === entry.module &&
				other.kind === entry.kind &&
				other.name === entry.name
		)
		return {
			...entry,
			name:
				entry.name +
				(collisions.length > 1 ? pascal(entry.version) : "") +
				(collisions.filter((other) => other.version === entry.version).length >
				1
					? pascal(entry.service.split(".").at(-1) ?? "")
					: "")
		}
	})
	const paths = new Set<string>()
	const manifest = []
	const modules = [...new Set(names.map((entry) => entry.module))].sort()
	for (const module of modules) {
		const entries = names.filter((entry) => entry.module === module)
		const hasTx = entries.some((entry) => entry.kind === "tx")
		const keys = `${camel(module)}Keys`
		await fs.mkdir(join(output, "react", module), { recursive: true })
		await fs.writeFile(
			join(output, "react", module, "keys.ts"),
			`${marker}\nimport type { ChainHookContext } from "../context.js"\nimport { sdkKeys } from "../options.js"\nexport const ${keys} = { all: (context: ChainHookContext) => sdkKeys.module(context, ${JSON.stringify(module)}) }\n`
		)
		for (const entry of entries) {
			const path = `react/${module}/${hasTx ? `${entry.kind}/` : ""}use-${kebab(entry.name)}.ts`
			if (paths.has(path)) throw new Error(`Hook naming collision: ${path}`)
			paths.add(path)
			const spec = (target: string) => {
				const value = relative(dirname(path), target)
				return value.startsWith(".") ? value : `./${value}`
			}
			const method = `${entry.symbol}.method.${entry.localName}`
			const context =
				entry.transport === "message" ? "ChainTxContext" : "ChainHookContext"
			const options = `${camel(entry.name)}${entry.kind === "query" ? "Query" : "Mutation"}Options`
			const id = JSON.stringify(`${entry.service}/${entry.method}`)
			const factory = entry.rpcFactory ?? entry.factory
			const transport =
				entry.rpcFactory || entry.transport === "rpc"
					? "context.rpc"
					: `requireRest(context, ${id})`
			const lines = [
				marker,
				`import type { MessageInitShape, MessageShape } from "${spec("index.js")}"`,
				`import { ${factory} } from "${spec(`${entry.file}_client.js`)}"`,
				`import { ${entry.symbol} } from "${spec(`${entry.file}_pb.js`)}"`,
				`import { ${entry.kind === "query" ? "useSuspenseQuery" : "useMutation, useQueryClient"} } from "@tanstack/react-query"`,
				`import { ${entry.transport === "rest" && !entry.rpcFactory ? "requireRest, " : ""}type ${context} } from "${spec("react/context.js")}"`,
				`import { sdkKeys, ${entry.kind === "query" ? "sdkQueryOptions" : `${entry.transport === "message" ? "sdkMessageMutationOptions" : "sdkServiceMutationOptions"}, invalidateIncludedTransaction`} } from "${spec("react/options.js")}"`,
				`export type ${entry.name}Request = MessageInitShape<typeof ${method}.input>`,
				entry.transport === "message"
					? `export type ${entry.name}MessageResponse = MessageShape<typeof ${method}.output>\nexport type ${entry.name}Response = Awaited<ReturnType<ChainTxContext["submit"]>>`
					: `export type ${entry.name}Response = MessageShape<typeof ${method}.output>`
			]
			if (entry.kind === "query") {
				lines.push(
					`export function ${options}(context: ${context}, input: ${entry.name}Request) { return sdkQueryOptions(sdkKeys.query(context, ${JSON.stringify(module)}, ${id}, ${method}.input, input), ${method}, input, ${factory}(${transport}).${entry.localName}) }`,
					`export function use${entry.name}(context: ${context}, input: ${entry.name}Request) { return useSuspenseQuery(${options}(context, input)) }`
				)
			} else {
				const key = `sdkKeys.tx(context, ${JSON.stringify(module)}, ${id}${entry.transport === "message" ? ", context.signerAddress" : ""})`
				lines.push(
					`export function ${options}(context: ${context}) { return ${entry.transport === "message" ? `sdkMessageMutationOptions(context, ${key}, ${factory}.${entry.localName})` : `sdkServiceMutationOptions(${key}, ${factory}(${transport}).${entry.localName})`} }`,
					`export function use${entry.name}(context: ${context}) { const cache = useQueryClient(); return useMutation({ ...${options}(context), onSuccess: result => invalidateIncludedTransaction(cache, context, result) }) }`
				)
				if (entry.transport === "message") {
					const nativeOptions = `${camel(entry.name)}NativeMutationOptions`
					lines.push(
						`import type { UseMutationResult } from "@tanstack/react-query"`,
						`import type { NativeChainTxContext } from "${spec("react/context.js")}"`,
						`import { sdkNativeMessageMutationOptions, type NativeMessageReceipt, type NativeMessageMutationOptions, type NativeMutationVariables } from "${spec("react/options.js")}"`,
						`export type ${entry.name}NativeResponse = NativeMessageReceipt<typeof ${method}.output>`,
						`export function ${nativeOptions}(context: NativeChainTxContext): NativeMessageMutationOptions<typeof ${method}.input, typeof ${method}.output> { return sdkNativeMessageMutationOptions(context, ${key}, ${method}) }`,
						`export function use${entry.name}Native(context: NativeChainTxContext): UseMutationResult<${entry.name}NativeResponse, Error, NativeMutationVariables<${entry.name}Request>> { return useMutation(${nativeOptions}(context)) }`
					)
				}
			}
			await fs.mkdir(join(output, dirname(path)), { recursive: true })
			await fs.writeFile(join(output, path), `${lines.join("\n")}\n`)
			manifest.push({
				operation: `${entry.service}/${entry.method}`,
				path,
				export: `use${entry.name}`,
				kind: entry.kind,
				module,
				input: entry.input,
				output: entry.output
			})
		}
	}
	await fs.writeFile(
		join(output, "react", "index.ts"),
		'export * from "./context.js"\nexport * from "./options.js"\n'
	)
	await fs.writeFile(
		join(output, "react", "hooks.json"),
		`${JSON.stringify({ modules, operations: manifest }, null, 2)}\n`
	)
}
