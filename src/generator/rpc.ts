import { promises as fs } from "node:fs"
import { join, relative } from "node:path"
import type { FileDescriptorProto } from "@bufbuild/protobuf/wkt"
import { compareImportBlocks, sanitizeAlias } from "./common.ts"
import { getModuleInfo } from "./utils.ts"

type ImportKind = "type" | "value"
type ImportEntry = { name: string; alias: string; kind: ImportKind }

type RpcMethodEntry = {
	name: string
	originalName: string
	requestType: string
	responseType: string
	requestSchema: string
	responseSchema: string
	callType: "unary" | "broadcastTx"
	serviceFullName: string
}

type RpcModuleEntry = {
	moduleName: string
	imports: Map<string, ImportEntry[]>
	aliases: Set<string>
	clients: Array<{
		funcName: string
		serviceName: string
		serviceFullName: string
		methods: RpcMethodEntry[]
	}>
}

const lowerFirst = (value: string) =>
	value.charAt(0).toLowerCase() + value.slice(1)

export const generateRpc = async (
	outPath: string,
	descriptors: FileDescriptorProto[],
	moduleIgnoreList: string[]
): Promise<void> => {
	const modules: Map<string, RpcModuleEntry> = new Map()

	const rpcDir = join(outPath, "rpc")
	await fs.rm(rpcDir, { recursive: true, force: true })

	const typeImportMap = buildTypeImportMap(descriptors)

	for (const file of descriptors) {
		if (!file.package || !file.service || file.service.length === 0) continue

		const packagePath = file.package.split(".").join("/")
		if (!packagePath.startsWith("cosmos/")) continue
		const moduleInfo = getModuleInfo(packagePath)
		if (!moduleInfo) continue
		if (moduleIgnoreList.includes(moduleInfo.moduleKey)) continue

		const protoBaseName = file.name
			? (file.name.split("/").pop()?.replace(".proto", "") ?? "index")
			: "index"
		const pathSuffix = sanitizeAlias(
			`${moduleInfo.versionName || "v"}_${protoBaseName}`
		)
		const descriptorImportPath = buildDescriptorImport(
			moduleInfo.versionSegments,
			protoBaseName
		)

		const moduleEntry: RpcModuleEntry = modules.get(moduleInfo.moduleKey) ?? {
			moduleName: moduleInfo.moduleName,
			imports: new Map<string, ImportEntry[]>(),
			aliases: new Set<string>(),
			clients: []
		}

		for (const service of file.service) {
			if (service.name === "Msg") continue

			const methods: RpcMethodEntry[] = []
			for (const method of service.method) {
				const serviceFullName = `${file.package}.${service.name}`

				const inputFull = method.inputType?.replace(/^\./, "") ?? ""
				const outputFull = method.outputType?.replace(/^\./, "") ?? ""
				const requestType =
					inputFull.split(".").pop() ?? `${method.name}Request`
				const responseType =
					outputFull.split(".").pop() ?? `${method.name}Response`
				const requestSchema = `${requestType}Schema`
				const responseSchema = `${responseType}Schema`

				const requestImportPath =
					typeImportMap.get(inputFull) ?? descriptorImportPath
				const responseImportPath =
					typeImportMap.get(outputFull) ?? descriptorImportPath

				const requestAlias = addImport(
					moduleEntry,
					requestImportPath,
					requestType,
					pathSuffix,
					"type"
				)
				const responseAlias = addImport(
					moduleEntry,
					responseImportPath,
					responseType,
					pathSuffix,
					"type"
				)
				const requestSchemaAlias = addImport(
					moduleEntry,
					requestImportPath,
					requestSchema,
					pathSuffix,
					"value"
				)
				const responseSchemaAlias = addImport(
					moduleEntry,
					responseImportPath,
					responseSchema,
					pathSuffix,
					"value"
				)

				const callType: RpcMethodEntry["callType"] =
					serviceFullName === "cosmos.tx.v1beta1.Service" &&
					method.name === "BroadcastTx"
						? "broadcastTx"
						: "unary"

				methods.push({
					name: lowerFirst(method.name),
					originalName: method.name,
					requestType: requestAlias,
					responseType: responseAlias,
					requestSchema: requestSchemaAlias,
					responseSchema: responseSchemaAlias,
					callType,
					serviceFullName
				})
			}

			if (methods.length > 0) {
				const funcName = `create${moduleInfo.moduleName}${moduleInfo.versionName}${service.name}RpcClient`
				moduleEntry.clients.push({
					funcName,
					serviceName: service.name,
					serviceFullName: `${file.package}.${service.name}`,
					methods
				})
			}
		}

		modules.set(moduleInfo.moduleKey, moduleEntry)
	}

	const modulesToWrite = Array.from(modules.entries()).filter(
		([, moduleData]) => moduleData.clients.length > 0
	)
	if (modulesToWrite.length === 0) {
		return
	}

	const rpcUtilsPath = await ensureRpcUtils(outPath)

	for (const [moduleKey, moduleData] of modulesToWrite.sort((a, b) =>
		a[0].localeCompare(b[0])
	)) {
		const moduleDir = join(outPath, moduleKey)
		await fs.mkdir(moduleDir, { recursive: true })
		const header = "// This file was generated by proto-gen. DO NOT EDIT.\n\n"

		const rpcUtilsImportPath = relative(moduleDir, rpcUtilsPath)
			.replace(/\\/g, "/")
			.replace(/^(?!--|\.\.).*/, "./$&")

		const importBlocks: Array<{ path: string; symbols: ImportEntry[] }> = [
			{
				path: "@bufbuild/protobuf",
				symbols: [
					{ name: "create", alias: "create", kind: "value" },
					{ name: "fromBinary", alias: "fromBinary", kind: "value" }
				]
			},
			{
				path: rpcUtilsImportPath,
				symbols: [
					{ name: "RpcCallOptions", alias: "RpcCallOptions", kind: "type" },
					{ name: "RpcClientConfig", alias: "RpcClientConfig", kind: "type" },
					{
						name: "createTendermintRpcTransport",
						alias: "createTendermintRpcTransport",
						kind: "value"
					}
				]
			},
			...Array.from(moduleData.imports.entries()).map(
				([importPath, entries]) => ({
					path: importPath,
					symbols: entries
				})
			)
		]

		const sortedImports = importBlocks
			.sort(compareImportBlocks)
			.map(({ path, symbols }) => renderImport(path, symbols))
			.join("")

		let source = `${header}${sortedImports}\n`

		for (const client of moduleData.clients.sort((a, b) =>
			a.funcName.localeCompare(b.funcName)
		)) {
			const clientMethods: string[] = []
			for (const method of client.methods) {
				if (method.callType === "broadcastTx") {
					clientMethods.push(`
  async ${method.name}(request: ${method.requestType}): Promise<${method.responseType}> {
    const requestMessage = create(${method.requestSchema}, request)
    const res = await transport.broadcastTxRaw(
      requestMessage.txBytes ?? new Uint8Array(),
      requestMessage.mode
    )

    const txResponse = create(${method.responseSchema}, {
      txResponse: {
        txhash: res.hash ?? "",
        code: res.code ?? 0,
        rawLog: res.log ?? "",
        data: res.data,
        height: res.height !== undefined ? BigInt(res.height) : undefined,
        codespace: res.codespace
      }
    })

    return txResponse
  }`)
					continue
				}

				clientMethods.push(`
  async ${method.name}(request: ${method.requestType}, options?: RpcCallOptions): Promise<${method.responseType}> {
    const requestMessage = create(${method.requestSchema}, request)
    const responseBytes = await transport.abciQuery({
      service: "${method.serviceFullName}",
      method: "${method.originalName}",
      requestSchema: ${method.requestSchema},
      responseSchema: ${method.responseSchema},
      request: requestMessage,
      height: options?.height,
      prove: options?.prove
    })
    return fromBinary(${method.responseSchema}, responseBytes)
  }`)
			}

			source += `\nexport const ${client.funcName} = (config: RpcClientConfig) => {
  const transport = createTendermintRpcTransport(config)
  return {${clientMethods.join(",\n")}
  }
}\n`
		}

		await fs.writeFile(join(moduleDir, "rpc.ts"), source.trimEnd(), "utf-8")
	}
}

const ensureRpcUtils = async (outPath: string) => {
	const commonDir = join(outPath, "common")
	await fs.mkdir(commonDir, { recursive: true })
	const header = "// This file was generated by proto-gen. DO NOT EDIT.\n\n"
	const rpcUtilsPath = join(commonDir, "rpcUtils.ts")
	const templatePath = new URL("./templates/rpcUtils.ts", import.meta.url)
	const body = await fs.readFile(templatePath, "utf-8")
	await fs.writeFile(rpcUtilsPath, `${header}${body}`, "utf-8")
	return rpcUtilsPath
}

const buildDescriptorImport = (
	versionSegments: string[],
	protoBaseName: string
) =>
	`./descriptor/${versionSegments.length ? `${versionSegments.join("/")}/` : ""}${protoBaseName}_pb`

const addImport = (
	moduleEntry: RpcModuleEntry,
	importPath: string,
	name: string,
	suffix: string,
	kind: ImportKind
) => {
	const imports = moduleEntry.imports.get(importPath) ?? []
	const existing = imports.find((i) => i.name === name)
	if (existing) {
		return existing.alias
	}
	let alias = name
	if (moduleEntry.aliases.has(alias)) {
		alias = `${name}_${suffix}`
	}
	moduleEntry.aliases.add(alias)
	imports.push({ name, alias, kind })
	moduleEntry.imports.set(importPath, imports)
	return alias
}

const renderImport = (path: string, entries: ImportEntry[]) => {
	const parts = entries
		.slice()
		.sort((a, b) => {
			if (a.kind !== b.kind) return a.kind === "type" ? -1 : 1
			return a.alias.localeCompare(b.alias)
		})
		.map((entry) => {
			const base =
				entry.name === entry.alias
					? entry.name
					: `${entry.name} as ${entry.alias}`
			return entry.kind === "type" ? `type ${base}` : base
		})
	return `import { ${parts.join(", ")} } from "${path}"\n`
}

const buildTypeImportMap = (descriptors: FileDescriptorProto[]) => {
	const map = new Map<string, string>()
	for (const file of descriptors) {
		if (!file.package || !file.name) continue
		const packagePath = file.package.split(".").join("/")
		const moduleInfo = getModuleInfo(packagePath)
		if (!moduleInfo) continue
		const protoBaseName =
			file.name.split("/").pop()?.replace(".proto", "") ?? "index"
		const importPath = buildDescriptorImport(
			moduleInfo.versionSegments,
			protoBaseName
		)

		for (const msg of file.messageType ?? []) {
			const fullName = `${file.package}.${msg.name}`
			map.set(fullName, importPath)
		}
	}
	return map
}
