import { promises as fs } from "node:fs"
import { join, relative } from "node:path"
import type { FileDescriptorProto } from "@bufbuild/protobuf/wkt"
import { compareImportBlocks, sanitizeAlias } from "./common.ts"
import { getModuleInfo } from "./utils.ts"

type ImportKind = "type" | "value"
type ImportEntry = { name: string; alias: string; kind: ImportKind }

type GrpcModuleEntry = {
	moduleName: string
	imports: Map<string, ImportEntry[]>
	aliases: Set<string>
	clients: Array<{ funcName: string; serviceAlias: string }>
}

export const generateGrpc = async (
	outPath: string,
	descriptors: FileDescriptorProto[],
	moduleIgnoreList: string[]
): Promise<void> => {
	const modules: Map<string, GrpcModuleEntry> = new Map()

	// wipe legacy directory
	await fs.rm(join(outPath, "grpc"), { recursive: true, force: true })

	for (const file of descriptors) {
		if (!file.service || file.service.length === 0 || !file.package) continue

		const packagePath = file.package.split(".").join("/")
		if (!packagePath.startsWith("cosmos/")) continue
		const moduleInfo = getModuleInfo(packagePath)
		if (!moduleInfo) continue
		if (moduleIgnoreList.includes(moduleInfo.moduleKey)) continue

		const moduleEntry: GrpcModuleEntry = modules.get(moduleInfo.moduleKey) ?? {
			moduleName: moduleInfo.moduleName,
			imports: new Map<string, ImportEntry[]>(),
			aliases: new Set<string>(),
			clients: []
		}

		const protoBaseName = file.name
			? (file.name.split("/").pop()?.replace(".proto", "") ?? "index")
			: "index"
		const descriptorImportPath = `./descriptor/${moduleInfo.versionSegments.length ? `${moduleInfo.versionSegments.join("/")}/` : ""}${protoBaseName}_pb`
		const pathSuffix = sanitizeAlias(
			`${moduleInfo.versionName || "v"}_${protoBaseName.split(".").pop() || "svc"}`
		)

		for (const service of file.service) {
			const serviceName = service.name
			if (serviceName === "Msg") continue

			const importEntries = moduleEntry.imports.get(descriptorImportPath) ?? []
			let alias = serviceName
			if (moduleEntry.aliases.has(alias)) {
				alias = `${serviceName}_${pathSuffix}`
			}
			moduleEntry.aliases.add(alias)
			importEntries.push({ name: serviceName, alias, kind: "value" })
			moduleEntry.imports.set(descriptorImportPath, importEntries)

			const funcName = `create${moduleInfo.moduleName}${moduleInfo.versionName}${serviceName}Client`
			moduleEntry.clients.push({ funcName, serviceAlias: alias })
		}

		modules.set(moduleInfo.moduleKey, moduleEntry)
	}

	const modulesToWrite = Array.from(modules.entries()).filter(
		([, moduleData]) => moduleData.clients.length > 0
	)
	if (modulesToWrite.length === 0) {
		return
	}

	const grpcUtilsPath = await ensureGrpcUtils(outPath)

	for (const [moduleKey, moduleData] of modulesToWrite.sort((a, b) =>
		a[0].localeCompare(b[0])
	)) {
		const moduleDir = join(outPath, moduleKey)
		await fs.mkdir(moduleDir, { recursive: true })
		const header = "// This file was generated by proto-gen. DO NOT EDIT.\n"
		const grpcUtilsImportPath = relative(moduleDir, grpcUtilsPath)
			.replace(/\\/g, "/")
			.replace(/^(?!--|\.\.).*/, "./$&")

		const importBlocks: Array<{ path: string; symbols: ImportEntry[] }> = [
			{
				path: "@connectrpc/connect",
				symbols: [
					{ name: "Client", alias: "Client", kind: "type" },
					{ name: "createClient", alias: "createClient", kind: "value" }
				]
			},
			{
				path: "@connectrpc/connect-node",
				symbols: [
					{
						name: "createGrpcTransport",
						alias: "createGrpcTransport",
						kind: "value"
					}
				]
			},
			{
				path: grpcUtilsImportPath,
				symbols: [
					{
						name: "ConfigurationError",
						alias: "ConfigurationError",
						kind: "value"
					},
					{ name: "ErrorUtils", alias: "ErrorUtils", kind: "value" },
					{ name: "GrpcClientConfig", alias: "GrpcClientConfig", kind: "type" },
					{ name: "GrpcError", alias: "GrpcError", kind: "value" },
					{ name: "NetworkError", alias: "NetworkError", kind: "value" },
					{ name: "withRetry", alias: "withRetry", kind: "value" }
				]
			},
			...Array.from(moduleData.imports.entries()).map(
				([importPath, entries]) => ({
					path: importPath,
					symbols: entries
				})
			)
		]

		const sortedImports = importBlocks
			.sort(compareImportBlocks)
			.map(({ path, symbols }) => renderImport(path, symbols))
			.join("")

		let source = `${header}${sortedImports}\n`

		for (const client of moduleData.clients.sort((a, b) =>
			a.funcName.localeCompare(b.funcName)
		)) {
			source += `export const ${client.funcName} = ({ baseUrl, retry, interceptors = [] }: GrpcClientConfig) => {
  if (!baseUrl) {
    throw new ConfigurationError("baseUrl is required for gRPC client")
  }

  const transport = createGrpcTransport({
    baseUrl,
    interceptors: [
      (next) => async (req) => {
        try {
          const res = await next(req)
          return res
        } catch (error) {
          if (error && typeof error === "object" && "code" in error) {
            throw GrpcError.fromConnectError(error)
          }
          if (error instanceof Error && error.message.includes("fetch")) {
            throw new NetworkError(error.message, {
              url: baseUrl,
              method: req.method.name,
              originalError: error
            })
          }
          throw ErrorUtils.fromUnknown(error, \`gRPC call to \${req.method.name} failed\`)
        }
      },
      ...interceptors
    ]
  })

  const client = createClient(${client.serviceAlias}, transport)

  if (retry) {
    return new Proxy(client, {
			get(target: Client<typeof ${client.serviceAlias}>, prop: keyof Client<typeof ${client.serviceAlias}>) {
				const original = target[prop]
				if (typeof original === "function") {
					return async (...args: unknown[]) => {
						return withRetry(
							() =>
								(
									original as (...fnArgs: unknown[]) => Promise<unknown>
								).apply(target, args),
							retry
						)
					}
				}
        return original
      }
    }) as Client<typeof ${client.serviceAlias}>
  }

  return client
}\n\n`
		}

		await fs.writeFile(join(moduleDir, "grpc.ts"), source.trimEnd(), "utf-8")
	}
}

const ensureGrpcUtils = async (outPath: string) => {
	const commonDir = join(outPath, "common")
	await fs.mkdir(commonDir, { recursive: true })
	const header = "// This file was generated by proto-gen. DO NOT EDIT.\n\n"
	const grpcUtilsPath = join(commonDir, "grpcUtils.ts")
	const templatePath = new URL("./templates/grpcUtils.ts", import.meta.url)
	const body = await fs.readFile(templatePath, "utf-8")
	await fs.writeFile(grpcUtilsPath, `${header}${body}`, "utf-8")
	return grpcUtilsPath
}

const renderImport = (path: string, entries: ImportEntry[]) => {
	const parts = entries
		.slice()
		.sort((a, b) => {
			if (a.kind !== b.kind) return a.kind === "type" ? -1 : 1
			return a.alias.localeCompare(b.alias)
		})
		.map((entry) => {
			const base =
				entry.name === entry.alias
					? entry.name
					: `${entry.name} as ${entry.alias}`
			return entry.kind === "type" ? `type ${base}` : base
		})
	return `import { ${parts.join(", ")} } from "${path}"\n`
}
